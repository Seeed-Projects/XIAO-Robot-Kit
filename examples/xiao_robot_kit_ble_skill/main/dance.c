static esp_err_t dance_set_arm_angles(int left_arm_angle, int right_arm_angle)
{
    esp_err_t left_err = left_arm_angle == DANCE_ARM_KEEP_ANGLE ? ESP_OK :
        servo_set_angle(DANCE_LEFT_ARM_SERVO_ID, left_arm_angle);
    esp_err_t right_err = right_arm_angle == DANCE_ARM_KEEP_ANGLE ? ESP_OK :
        servo_set_angle(DANCE_RIGHT_ARM_SERVO_ID, right_arm_angle);
    return left_err != ESP_OK ? left_err : right_err;
}

static void dance_set_arms_down(void)
{
    (void)dance_set_arm_angles(DANCE_LEFT_ARM_DOWN_ANGLE, DANCE_RIGHT_ARM_DOWN_ANGLE);
}

static bool dance_is_cancelled(void)
{
    xSemaphoreTake(dance_mutex, portMAX_DELAY);
    bool cancelled = dance_cancelled;
    xSemaphoreGive(dance_mutex);
    return cancelled;
}

static void dance_track_heading(float *yaw_degrees, int64_t *previous_sample_us,
                                bool *tracking_enabled)
{
    if (!*tracking_enabled) {
        return;
    }

    float yaw_rate_dps;
    esp_err_t err = chassis_action_read_calibrated_yaw_rate(&yaw_rate_dps);
    if (err != ESP_OK) {
        *tracking_enabled = false;
        ESP_LOGW(TAG, "Heading tracking disabled: %s", esp_err_to_name(err));
        return;
    }

    int64_t now_us = esp_timer_get_time();
    *yaw_degrees += yaw_rate_dps * (float)(now_us - *previous_sample_us) / 1000000.0f;
    *previous_sample_us = now_us;
}

static bool dance_wait_step(uint32_t duration_ms, float *yaw_degrees,
                            int64_t *previous_sample_us, bool *tracking_enabled)
{
    int64_t deadline_us = esp_timer_get_time() + (int64_t)duration_ms * 1000;
    while (esp_timer_get_time() < deadline_us) {
        int64_t remaining_us = deadline_us - esp_timer_get_time();
        uint32_t wait_ms = (uint32_t)(remaining_us / 1000);
        if (wait_ms > BELIEVER_YAW_SAMPLE_PERIOD_MS) {
            wait_ms = BELIEVER_YAW_SAMPLE_PERIOD_MS;
        }
        if (wait_ms == 0) {
            wait_ms = 1;
        }
        if (ulTaskNotifyTake(pdTRUE, pdMS_TO_TICKS(wait_ms)) != 0) {
            return false;
        }
        if (yaw_degrees != NULL) {
            dance_track_heading(yaw_degrees, previous_sample_us, tracking_enabled);
        }
    }
    return !dance_is_cancelled();
}

static bool dance_step_is_translation(const dance_step_t *step)
{
    if (!step->set_speed || step->left_speed == 0 || step->right_speed == 0) {
        return false;
    }

    return (step->left_speed > 0 && step->right_speed > 0) ||
           (step->left_speed < 0 && step->right_speed < 0);
}

static uint32_t dance_translation_active_ms(uint32_t duration_ms)
{
    uint32_t active_ms = (duration_ms * BELIEVER_TRANSLATION_ACTIVE_PERCENT) / 100;
    return active_ms == 0 ? 1 : active_ms;
}

static bool dance_run_step(const dance_step_t *step, float *yaw_degrees,
                           int64_t *previous_sample_us, bool *tracking_enabled)
{
    xSemaphoreTake(dance_mutex, portMAX_DELAY);
    bool cancelled = dance_cancelled;
    esp_err_t err = ESP_OK;
    if (!cancelled && step->set_speed) {
        err = speed_control_set_target(step->left_speed, step->right_speed);
    }
    if (!cancelled && err == ESP_OK && step->set_arms) {
        err = dance_set_arm_angles(step->left_arm_angle, step->right_arm_angle);
    }
    xSemaphoreGive(dance_mutex);

    if (cancelled || err != ESP_OK) {
        return false;
    }

    if (dance_step_is_translation(step)) {
        uint32_t active_ms = dance_translation_active_ms(step->duration_ms);
        if (!dance_wait_step(active_ms, yaw_degrees, previous_sample_us, tracking_enabled)) {
            speed_control_stop();
            return false;
        }

        speed_control_stop();
        return dance_wait_step(step->duration_ms - active_ms, yaw_degrees,
                               previous_sample_us, tracking_enabled);
    }

    return dance_wait_step(step->duration_ms, yaw_degrees, previous_sample_us, tracking_enabled);
}

static float dance_normalize_heading(float yaw_degrees)
{
    float heading_error_degrees = fmodf(yaw_degrees, 360.0f);
    if (heading_error_degrees > 180.0f) {
        heading_error_degrees -= 360.0f;
    } else if (heading_error_degrees < -180.0f) {
        heading_error_degrees += 360.0f;
    }
    return heading_error_degrees;
}

static bool dance_return_believer_to_initial_heading(float dance_yaw_degrees)
{
    float heading_error_degrees = dance_normalize_heading(dance_yaw_degrees);

    if (fabsf(heading_error_degrees) < BELIEVER_HEADING_RETURN_DEADBAND_DEGREES) {
        ESP_LOGI(TAG, "Believer heading drift %.1f deg is within the deadband",
                 (double)heading_error_degrees);
        return true;
    }

    /* Turn opposite to the accumulated yaw through the shortest angular path. */
    float target_turn_degrees = fabsf(heading_error_degrees);
    int turn_speed = heading_error_degrees > 0.0f ? -BELIEVER_SPEED_SHAKE
                                                  : BELIEVER_SPEED_SHAKE;
    esp_err_t err = speed_control_set_target(turn_speed, -turn_speed);
    if (err != ESP_OK) {
        ESP_LOGW(TAG, "Believer heading return could not start: %s", esp_err_to_name(err));
        return false;
    }

    float returned_degrees = 0.0f;
    int64_t previous_sample_us = esp_timer_get_time();
    int64_t deadline_us = previous_sample_us +
                          (int64_t)BELIEVER_HEADING_RETURN_TIMEOUT_MS * 1000;
    while (esp_timer_get_time() < deadline_us) {
        if (dance_is_cancelled()) {
            speed_control_stop();
            return false;
        }
        vTaskDelay(pdMS_TO_TICKS(BELIEVER_YAW_SAMPLE_PERIOD_MS));

        float yaw_rate_dps;
        err = chassis_action_read_calibrated_yaw_rate(&yaw_rate_dps);
        if (err != ESP_OK) {
            speed_control_stop();
            ESP_LOGW(TAG, "Believer heading return stopped: %s", esp_err_to_name(err));
            return false;
        }
        int64_t now_us = esp_timer_get_time();
        returned_degrees += yaw_rate_dps * (float)(now_us - previous_sample_us) / 1000000.0f;
        previous_sample_us = now_us;
        if (fabsf(returned_degrees) >= target_turn_degrees) {
            speed_control_stop();
            ESP_LOGI(TAG, "Believer heading restored: error %.1f deg, shortest return %.1f deg",
                     (double)heading_error_degrees, (double)returned_degrees);
            return true;
        }
    }

    speed_control_stop();
    ESP_LOGW(TAG, "Believer heading return timed out at %.1f of %.1f deg",
             (double)returned_degrees, (double)target_turn_degrees);
    return false;
}

static bool dance_restore_believer_heading(float dance_yaw_degrees, bool tracking_enabled)
{
    speed_control_stop();
    if (!tracking_enabled) {
        ESP_LOGW(TAG, "Believer heading return skipped: IMU tracking unavailable");
        return true;
    }

    return dance_return_believer_to_initial_heading(dance_yaw_degrees);
}

static void dance_task_entry(void *arg)
{
    const dance_program_t *program = arg;
    bool completed = true;
    bool tracking_believer_yaw = program == &believer_program ||
                                 program == &new_believer_program;
    float believer_yaw_degrees = 0.0f;
    int64_t previous_yaw_sample_us = esp_timer_get_time();

    if (program->start_delay_ms > 0) {
        completed = dance_wait_step(program->start_delay_ms, NULL, &previous_yaw_sample_us,
                                    &tracking_believer_yaw);
        previous_yaw_sample_us = esp_timer_get_time();
    }

    for (size_t group = 0; group < program->group_count && completed; ++group) {
        for (size_t cycle = 0; cycle < program->cycles_per_group && completed; ++cycle) {
            for (size_t step = 0; step < program->cycle_step_count; ++step) {
                completed = dance_run_step(&program->cycle[step],
                                           tracking_believer_yaw ? &believer_yaw_degrees : NULL,
                                           &previous_yaw_sample_us, &tracking_believer_yaw);
                if (!completed) {
                    break;
                }
            }
        }

        if (completed && program->run_group_spin) {
            for (size_t step = 0; step < sizeof(dance_spin) / sizeof(dance_spin[0]); ++step) {
                completed = dance_run_step(&dance_spin[step], NULL, &previous_yaw_sample_us,
                                           &tracking_believer_yaw);
                if (!completed) {
                    break;
                }
            }
        }
    }

    if (completed && (program == &believer_program || program == &new_believer_program)) {
        completed = dance_restore_believer_heading(believer_yaw_degrees,
                                                   tracking_believer_yaw);
    }

    xSemaphoreTake(dance_mutex, portMAX_DELAY);
    if (!dance_cancelled) {
        speed_control_stop();
    }
    if (program->set_arms_down_on_completion || dance_cancelled) {
        dance_set_arms_down();
    }
    dance_task = NULL;
    xSemaphoreGive(dance_mutex);
    xSemaphoreGive(dance_completion);
    vTaskDelete(NULL);
}

esp_err_t dance_init(void)
{
    if (dance_mutex != NULL && dance_completion != NULL) {
        return ESP_OK;
    }

    if (dance_mutex == NULL) {
        dance_mutex = xSemaphoreCreateMutex();
        if (dance_mutex == NULL) {
            return ESP_ERR_NO_MEM;
        }
    }
    if (dance_completion == NULL) {
        dance_completion = xSemaphoreCreateBinary();
        if (dance_completion == NULL) {
            return ESP_ERR_NO_MEM;
        }
    }
    return ESP_OK;
}

static esp_err_t dance_start_program(const dance_program_t *program, const char *task_name)
{
    if (dance_mutex == NULL) {
        return ESP_ERR_INVALID_STATE;
    }

    xSemaphoreTake(dance_mutex, portMAX_DELAY);
    if (dance_task != NULL) {
        xSemaphoreGive(dance_mutex);
        return ESP_ERR_INVALID_STATE;
    }

    while (xSemaphoreTake(dance_completion, 0) == pdTRUE) {
    }
    speed_control_stop();
    dance_cancelled = false;
    if (xTaskCreate(dance_task_entry, task_name, DANCE_TASK_STACK_SIZE, (void *)program,
                    DANCE_TASK_PRIORITY, &dance_task) != pdPASS) {
        dance_task = NULL;
        xSemaphoreGive(dance_mutex);
        return ESP_ERR_NO_MEM;
    }
    xSemaphoreGive(dance_mutex);
    return ESP_OK;
}

