/*
 * Take Me Hand: 128 BPM, 4/4. This choreography uses a 673 ms count-in so
 * the first move lands on the first downbeat, then runs 32 four-beat bars at
 * 469 ms per beat (60.705 s total). Each section has a distinct movement
 * phrase: wake-up, side steps, travel, build, chorus, spin accents and a
 * closed final pose. The left/right names below refer to physical arms, not
 * servo numbering.
 */

#define TAKEHAND_HALF_BEAT_A_MS (DANCE_TAKEHAND_BEAT_MS / 2)               /* 234 ms */
#define TAKEHAND_HALF_BEAT_B_MS (DANCE_TAKEHAND_BEAT_MS - TAKEHAND_HALF_BEAT_A_MS) /* 235 ms */

/* Wheel speeds are closed-loop percent targets (-100..100), per bar. */
#define TAKEHAND_SPEED_SOFT      46
#define TAKEHAND_SPEED_ROLL      58
#define TAKEHAND_SPEED_GLIDE     64
#define TAKEHAND_SPEED_ARC_INNER 30
#define TAKEHAND_SPEED_ARC_OUTER 68
#define TAKEHAND_SPEED_TWIST     62
#define TAKEHAND_SPEED_PIVOT     60
#define TAKEHAND_SPEED_SPIN      72
#define TAKEHAND_SPEED_SHIMMY    76

/* Five-level mirrored arm map: 120 degrees of usable travel (30..150). */
#define TAKEHAND_LEFT_ARM_DOWN_POSE  150
#define TAKEHAND_LEFT_ARM_LOW_POSE   128
#define TAKEHAND_LEFT_ARM_MID_POSE    90
#define TAKEHAND_LEFT_ARM_HIGH_POSE   52
#define TAKEHAND_LEFT_ARM_UP_POSE     30

#define TAKEHAND_RIGHT_ARM_DOWN_POSE  30
#define TAKEHAND_RIGHT_ARM_LOW_POSE   52
#define TAKEHAND_RIGHT_ARM_MID_POSE   90
#define TAKEHAND_RIGHT_ARM_HIGH_POSE 128
#define TAKEHAND_RIGHT_ARM_UP_POSE   150

/* Wheels keep their target through the second half; only the arm pose changes. */
#define TH_FLOW_BEAT(L_SPEED, R_SPEED, L1, R1, L2, R2) \
    { true,  true, L_SPEED, R_SPEED, L1, R1, TAKEHAND_HALF_BEAT_A_MS }, \
    { false, true, 0,       0,       L2, R2, TAKEHAND_HALF_BEAT_B_MS }

/* Two wheel targets inside one beat for body shakes and rapid reversals. */
#define TH_SWITCH_BEAT(L1_SPEED, R1_SPEED, A1L, A1R, \
                       L2_SPEED, R2_SPEED, A2L, A2R) \
    { true, true, L1_SPEED, R1_SPEED, A1L, A1R, TAKEHAND_HALF_BEAT_A_MS }, \
    { true, true, L2_SPEED, R2_SPEED, A2L, A2R, TAKEHAND_HALF_BEAT_B_MS }

#define TH_STOP_BEAT(L1, R1, L2, R2) \
    TH_FLOW_BEAT(0, 0, L1, R1, L2, R2)

/* 1. Closed wake-up, then each outside arm follows the direction of the turn. */
#define TAKEHAND_BAR_OPENING \
    TH_STOP_BEAT(TAKEHAND_LEFT_ARM_DOWN_POSE, TAKEHAND_RIGHT_ARM_DOWN_POSE, \
                 TAKEHAND_LEFT_ARM_MID_POSE, TAKEHAND_RIGHT_ARM_MID_POSE), \
    TH_FLOW_BEAT(-TAKEHAND_SPEED_SOFT, TAKEHAND_SPEED_SOFT, \
                 TAKEHAND_LEFT_ARM_LOW_POSE, TAKEHAND_RIGHT_ARM_HIGH_POSE, \
                 TAKEHAND_LEFT_ARM_DOWN_POSE, TAKEHAND_RIGHT_ARM_UP_POSE), \
    TH_FLOW_BEAT(TAKEHAND_SPEED_SOFT, -TAKEHAND_SPEED_SOFT, \
                 TAKEHAND_LEFT_ARM_HIGH_POSE, TAKEHAND_RIGHT_ARM_LOW_POSE, \
                 TAKEHAND_LEFT_ARM_UP_POSE, TAKEHAND_RIGHT_ARM_DOWN_POSE), \
    TH_FLOW_BEAT(TAKEHAND_SPEED_ROLL, TAKEHAND_SPEED_ROLL, \
                 TAKEHAND_LEFT_ARM_HIGH_POSE, TAKEHAND_RIGHT_ARM_HIGH_POSE, \
                 TAKEHAND_LEFT_ARM_UP_POSE, TAKEHAND_RIGHT_ARM_UP_POSE)

/* 2. S curve: the arm on the outside of each curve opens as the body changes side. */
#define TAKEHAND_BAR_S_CURVE \
    TH_FLOW_BEAT(TAKEHAND_SPEED_ARC_INNER, TAKEHAND_SPEED_ARC_OUTER, \
                 TAKEHAND_LEFT_ARM_LOW_POSE, TAKEHAND_RIGHT_ARM_HIGH_POSE, \
                 TAKEHAND_LEFT_ARM_DOWN_POSE, TAKEHAND_RIGHT_ARM_UP_POSE), \
    TH_FLOW_BEAT(TAKEHAND_SPEED_ARC_OUTER, TAKEHAND_SPEED_ARC_INNER, \
                 TAKEHAND_LEFT_ARM_HIGH_POSE, TAKEHAND_RIGHT_ARM_LOW_POSE, \
                 TAKEHAND_LEFT_ARM_UP_POSE, TAKEHAND_RIGHT_ARM_DOWN_POSE), \
    TH_FLOW_BEAT(-TAKEHAND_SPEED_ARC_INNER, -TAKEHAND_SPEED_ARC_OUTER, \
                 TAKEHAND_LEFT_ARM_HIGH_POSE, TAKEHAND_RIGHT_ARM_LOW_POSE, \
                 TAKEHAND_LEFT_ARM_MID_POSE, TAKEHAND_RIGHT_ARM_DOWN_POSE), \
    TH_FLOW_BEAT(-TAKEHAND_SPEED_ARC_OUTER, -TAKEHAND_SPEED_ARC_INNER, \
                 TAKEHAND_LEFT_ARM_LOW_POSE, TAKEHAND_RIGHT_ARM_HIGH_POSE, \
                 TAKEHAND_LEFT_ARM_MID_POSE, TAKEHAND_RIGHT_ARM_MID_POSE)

/* 3. Forward motion opens the body; reverse motion pulls both arms inward. */
#define TAKEHAND_BAR_ROLL_BACK \
    TH_FLOW_BEAT(TAKEHAND_SPEED_ROLL, TAKEHAND_SPEED_ROLL, \
                 TAKEHAND_LEFT_ARM_MID_POSE, TAKEHAND_RIGHT_ARM_MID_POSE, \
                 TAKEHAND_LEFT_ARM_UP_POSE, TAKEHAND_RIGHT_ARM_UP_POSE), \
    TH_FLOW_BEAT(TAKEHAND_SPEED_GLIDE, TAKEHAND_SPEED_GLIDE, \
                 TAKEHAND_LEFT_ARM_UP_POSE, TAKEHAND_RIGHT_ARM_UP_POSE, \
