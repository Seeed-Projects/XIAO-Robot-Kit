esp_err_t dance_cancel(void)
{
    if (dance_mutex == NULL || dance_completion == NULL) {
        return ESP_ERR_INVALID_STATE;
    }

    xSemaphoreTake(dance_mutex, portMAX_DELAY);
    dance_cancelled = true;
    TaskHandle_t task = dance_task;
    if (task != NULL) {
        xTaskNotifyGive(task);
        speed_control_stop();
        dance_set_arms_down();
    }
    xSemaphoreGive(dance_mutex);

    return task == NULL ||
                   xSemaphoreTake(dance_completion, pdMS_TO_TICKS(DANCE_CANCEL_TIMEOUT_MS)) == pdTRUE
               ? ESP_OK
               : ESP_ERR_TIMEOUT;
}

bool dance_is_active(void)
{
    if (dance_mutex == NULL) {
        return false;
    }

    xSemaphoreTake(dance_mutex, portMAX_DELAY);
    bool active = dance_task != NULL;
    xSemaphoreGive(dance_mutex);
    return active;
}

void dance_stop(void)
{
    (void)dance_cancel();
}
